// Flatten for search
export function flattenNav(entries: NavEntry[]): NavEntry[] {
  const result: NavEntry[] = [];
  for (const entry of entries) {
    result.push(entry);
    if (entry.children) {
      result.push(...flattenNav(entry.children));
    }
  }
  return result;
}
